/**
 * Returns the appropriate form template based on job type and optional property type.
 * Template selection happens only at form creation time — existing forms are never affected.
 */
export function getFormTemplate(
  jobType: string,
  propertyType?: string
): Array<{ section: string; items: string[] }> {
  switch (jobType) {
    case "maintenance":
      return MAINTENANCE_FORM_TEMPLATE;
    case "move_in_out":
      return MOVE_IN_OUT_FORM_TEMPLATE;
    case "post_construction":
      return POST_CONSTRUCTION_FORM_TEMPLATE;
    default:
      // Commercial/office standard or deep cleans use the commercial template
      if (
        (propertyType === "commercial" || propertyType === "office") &&
        (jobType === "standard" || jobType === "deep_clean")
      ) {
        return COMMERCIAL_FORM_TEMPLATE;
      }
      // turnover, standard/deep_clean on residential/vacation_rental, and any other combo
      return FORM_TEMPLATE;
  }
}

